    // One-time migration: copies every book currently hard-coded in BIBLE_STUDIES_DATA
    // into the bible_study_books table, so they become regular database-backed books
    // that show up (and can be edited) here too. Runs in the admin's own browser via the
    // same supabaseClient the rest of the app uses — this is what actually reaches the
    // database, since this session's own sandbox can't call your Supabase project
    // directly (it's blocked by network policy, same as any other outside host).
    // Books already present in the database are left alone, so this is safe to run more
    // than once (e.g. after adding a new hard-coded book later).
    export async function importHardcodedBooksToDB() {
      if (!currentUser || !currentUser.isAdmin) return;

      const titlesToImport = Object.keys(BIBLE_STUDIES_DATA).filter(title => !bibleStudyDbBooks[title]);
      if (titlesToImport.length === 0) {
        alert('Nothing to import — every built-in book is already in the database.');
        return;
      }
      if (!confirm(`Import ${titlesToImport.length} book${titlesToImport.length === 1 ? '' : 's'} into the database?\n\n${titlesToImport.join(', ')}`)) return;

      const rows = titlesToImport.map(title => {
        const custom = BIBLE_STUDIES_DATA[title];
        let presenters = [];
        if (Array.isArray(custom.presenters)) presenters = custom.presenters;
        else if (custom.presenter) presenters = [custom.presenter];
        return {
          book: title,
          color: custom.color || null,
          height: custom.height || null,
          live: !!custom.live,
          shelf_group_id: null, // imported books start ungrouped — an admin can assign one afterward
          presenters: presenters,
          sessions: custom.sessions || [],
          updated_at: new Date().toISOString()
        };
      });

      const { data, error } = await bibleStudyBooksTable.upsertMany(
        rows,
        'id, book, color, height, live, shelf_group_id, presenters, sessions',
        { onConflict: 'book' }
      );

      if (error) {
        console.error('Error importing existing books:', error.message);
        alert('Import failed: ' + error.message + '\n\nMake sure the bible_study_books table has been created in Supabase (see the comment above loadBibleStudyBooksFromDB in this file for the SQL).');
        return;
      }

      (data || []).forEach(r => {
        bibleStudyDbBooks[r.book] = {
          dbId: r.id,
          color: r.color,
          height: r.height,
          live: !!r.live,
          shelfGroupId: r.shelf_group_id,
          presenters: r.presenters || [],
          sessions: r.sessions || []
        };
      });

      updateStudyNotificationBadges();
      renderBibleStudyShelf();
      alert(`Imported ${data ? data.length : titlesToImport.length} book(s). They're now editable from this screen.`);
    }