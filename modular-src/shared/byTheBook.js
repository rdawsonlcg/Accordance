    export let studyPresentersList = []; // [{ id, name, photo_url }]
    export let studyPresentersLoadError = null; // set if the table couldn't be read (missing table, RLS, etc.)

    export async function loadStudyPresenters() {
      studyPresentersLoadError = null;
      try {
        studyPresentersList = await fetchAllRows('study_presenters', 'id, name, photo_url', null, 'name');
      } catch (e) {
        // Table may not exist yet, or Row Level Security is blocking reads — surface this
        // in the dropdown itself (see populateStudyPresenterDropdowns) instead of only the
        // console, since an admin has no reason to check dev tools otherwise.
        console.error('Error loading study presenters:', e.message);
        studyPresentersLoadError = e.message;
        studyPresentersList = [];
      }
    }

    export const studyPresentersTable = createTableAccessor('study_presenters');

    // Adds a presenter to the reusable directory if it's not already there (matched by
    // name, case-insensitive). Safe to call every time a book is saved.
    // Returns true on success, false on a real failure (e.g. an RLS block on writes) so
    // callers can surface it instead of it disappearing into the console.
    export async function upsertStudyPresenter(name, photo) {
      const cleanName = (name || '').trim();
      const cleanPhoto = (photo || '').trim();
      if (!cleanName || !cleanPhoto) return true;
      const existing = studyPresentersList.find(p => p.name.toLowerCase() === cleanName.toLowerCase());
      if (existing) {
        if (existing.photo_url !== cleanPhoto) {
          // Keep the directory's photo current if it was edited on this book.
          const { error } = await studyPresentersTable.update(existing.id, { photo_url: cleanPhoto });
          if (!error) { existing.photo_url = cleanPhoto; return true; }
          console.error('Error updating study presenter photo:', error.message);
          return false;
        }
        return true;
      }
      try {
        const { data, error } = await studyPresentersTable.insert({ name: cleanName, photo_url: cleanPhoto }, 'id, name, photo_url');
        if (error) throw error;
        studyPresentersList.push(data);
        studyPresentersList.sort((a, b) => a.name.localeCompare(b.name));
        return true;
      } catch (e) {
        console.error('Error adding study presenter:', e.message);
        return false;
      }
    }

    // One-time backfill: if the directory is empty (freshly created table), seed it from
    // every presenter already used across all books — hardcoded and DB-saved alike —
    // so the dropdown isn't empty the very first time an admin opens this view. If writes
    // fail (e.g. Row Level Security blocking inserts while still allowing reads — which
    // shows up as "table reads fine but stays empty"), that's surfaced the same way a
    // read failure is, via studyPresentersLoadError, instead of only the console.
    export async function seedStudyPresentersFromExistingBooksIfEmpty() {
      if (studyPresentersList.length > 0) return;
      const seen = new Map(); // name (lowercase) -> { name, photo }
      BIBLE_STUDIES_BOOK_ORDER.forEach((title, index) => {
        const cfg = getBibleStudyBookConfig(title, index);
        (cfg.presenters || []).forEach(p => {
          if (p && p.name && p.photo && !seen.has(p.name.toLowerCase())) seen.set(p.name.toLowerCase(), p);
        });
        (cfg.sessions || []).forEach(s => {
          if (s && s.presenter && s.presenter.name && s.presenter.photo && !seen.has(s.presenter.name.toLowerCase())) {
            seen.set(s.presenter.name.toLowerCase(), s.presenter);
          }
        });
      });
      if (seen.size === 0) return;
      let failures = 0;
      for (const p of seen.values()) {
        const ok = await upsertStudyPresenter(p.name, p.photo);
        if (!ok) failures++;
      }
      if (failures > 0 && studyPresentersList.length === 0) {
        studyPresentersLoadError = `Found ${seen.size} presenter(s) in your existing books, but saving ${failures} of them to the "study_presenters" table failed — most likely Row Level Security is blocking writes even though reads work. Try running: alter table study_presenters disable row level security; then reopen this screen, or add presenters manually below in the meantime.`;
      }
    }

    // Populates every "Choose existing presenter" dropdown currently in the book admin
    // form with the current directory contents.
    export function populateStudyPresenterDropdowns() {
      let placeholder = 'Choose an existing presenter…';
      if (studyPresentersLoadError) {
        placeholder = '⚠ Could not load presenters — see below';
      } else if (studyPresentersList.length === 0) {
        placeholder = 'No presenters saved yet — add one below';
      }
      document.querySelectorAll('.study-presenter-picker').forEach(select => {
        const current = select.value;
        select.innerHTML = `<option value="">${placeholder}</option>` +
          studyPresentersList.map(p => `<option value="${p.id}">${(p.name || '').replace(/</g, '&lt;')}</option>`).join('');
        select.value = current && studyPresentersList.some(p => String(p.id) === current) ? current : '';
      });

      document.querySelectorAll('.study-presenter-picker-error-note').forEach(note => {
        if (studyPresentersLoadError) {
          note.style.display = 'block';
          note.innerText = `Presenter list failed to load: ${studyPresentersLoadError}. This is usually because the "study_presenters" table hasn't been created yet, or Row Level Security is blocking reads — see the comment above loadStudyPresenters() in this file for the setup SQL.`;
        } else {
          note.style.display = 'none';
        }
      });
    }

    export async function loadBibleStudyBooksFromDB() {
      try {
        const rows = await fetchAllRows('bible_study_books', 'id, book, color, height, live, shelf_group_id, presenters, sessions');
        const map = {};
        rows.forEach(r => {
          map[r.book] = {
            dbId: r.id,
            color: r.color,
            height: r.height,
            live: !!r.live,
            shelfGroupId: r.shelf_group_id,
            presenters: Array.isArray(r.presenters) ? r.presenters : [],
            sessions: Array.isArray(r.sessions) ? r.sessions.map(s => ({ ...s, title: fixMojibakeText(s.title || '') })) : []
          };
        });
        bibleStudyDbBooks = map;
      } catch (e) {
        // Table may not exist yet (first-time setup) — fall back to BIBLE_STUDIES_DATA only.
        console.error('Error loading Books of the Bible admin content:', e.message);
      }
    }

    export function getBibleStudyBookConfig(title, index) {
      const dbRow = bibleStudyDbBooks[title];
      const custom = dbRow || BIBLE_STUDIES_DATA[title];
      // Supports both the older single `presenter` field (existing books) and the
      // newer `presenters` array (for books with more than one presenter) — always
      // normalized to an array here so the renderer only has to handle one shape.
      let presenters = [];
      if (custom) {
        if (Array.isArray(custom.presenters)) {
          presenters = custom.presenters;
        } else if (custom.presenter) {
          presenters = [custom.presenter];
        }
      }
      // A book in a shelf group takes its color/height from the group (shared
      // across every book in it) rather than from its own row — that's what
      // makes editing a group's color update every book in it at once.
      const shelfGroupId = dbRow ? dbRow.shelfGroupId : null;
      const shelfGroup = (shelfGroupId != null) ? bookShelfGroupsList.find(g => g.id === shelfGroupId) : null;
      return {
        title,
        dbId: dbRow ? dbRow.dbId : null,
        shelfGroupId: shelfGroupId,
        color: (shelfGroup && shelfGroup.color) || (custom && custom.color) || BIBLE_STUDIES_DEFAULT_COLORS[index % BIBLE_STUDIES_DEFAULT_COLORS.length],
        height: (shelfGroup && shelfGroup.height) || (custom && custom.height) || BIBLE_STUDIES_DEFAULT_HEIGHTS[index % BIBLE_STUDIES_DEFAULT_HEIGHTS.length],
        live: !!(custom && custom.live),
        presenters: presenters,
        sessions: custom ? (custom.sessions || []) : []
      };
    }

    // Canonical display order for the color-code legend — traditional section
    // groupings rather than alphabetical, so the legend reads the way these
    // testaments are conventionally divided. A group whose name matches one of
    // these (case-insensitively) sorts into that position; any other group
    // name (a custom grouping an admin made up) just falls in after these,
    // alphabetically.
    export const OT_GROUP_ORDER = ['The Law', 'The Former Prophets', 'The Writings', 'The Major Prophets', 'The Minor Prophets'];
    export const NT_GROUP_ORDER = ['The Gospels & Acts', 'The Epistles of Paul', 'The General Epistles', 'Revelation'];

    export function sortGroupsByCanonicalOrder(groups, order) {
      function rank(name) {
        const idx = order.findIndex(o => o.toLowerCase() === name.trim().toLowerCase());
        return idx === -1 ? order.length : idx;
      }
      return groups.slice().sort((a, b) => {
        const ra = rank(a.name), rb = rank(b.name);
        if (ra !== rb) return ra - rb;
        return a.name.localeCompare(b.name);
      });
    }

    // Color-code reference shown above the shelf: one swatch per named shelf
    // group that has at least one member book in that testament (a book's own
    // individual color isn't listed here — only groups act as a shared "code",
    // since that's the only case where the same color maps to more than one
    // book). Re-run this any time the shelf itself re-renders so it always
    // matches the current groups.
    export function renderBibleStudyColorLegend() {
      const otContainer = document.getElementById('bible-study-color-codes-ot');
      const ntContainer = document.getElementById('bible-study-color-codes-nt');
      if (!otContainer || !ntContainer) return;

      const otGroupIds = new Set();
      const ntGroupIds = new Set();
      BIBLE_STUDIES_BOOK_ORDER.forEach((title, i) => {
        const cfg = getBibleStudyBookConfig(title, i);
        if (cfg.shelfGroupId != null) {
          (i < OT_BOOK_COUNT ? otGroupIds : ntGroupIds).add(cfg.shelfGroupId);
        }
      });

      function buildItemsHtml(groupIds, order) {
        if (groupIds.size === 0) {
          return '<div class="bible-study-color-code-empty">No color groups yet — assign one in Manage Content.</div>';
        }
        const groups = sortGroupsByCanonicalOrder(bookShelfGroupsList.filter(g => groupIds.has(g.id)), order);
        return groups.map(g => `
          <div class="bible-study-color-code-item">
            <span class="bible-study-color-code-swatch" style="background:${g.color};"></span>
            <span>${escapeHtml(g.name)}</span>
          </div>`).join('');
      }

      otContainer.innerHTML = buildItemsHtml(otGroupIds, OT_GROUP_ORDER);
      ntContainer.innerHTML = buildItemsHtml(ntGroupIds, NT_GROUP_ORDER);
    }

    // Pixel-aligns the two dimension-line rulers to the actual spines below
    // them (Genesis→Malachi, Matthew→Revelation) and keeps them sliding in
    // lockstep with the shelf's own horizontal scroll. The ruler track is
    // sized to the shelf's full scrollWidth and each line is positioned at
    // that book's real on-shelf coordinates, so it always starts flush with
    // the left edge of its first book and ends flush with the right edge of
    // its last — no matter how far the shelf has been scrolled.
    // Draws one dimension line's full width — both end ticks plus the
    // connecting rule — into its <svg>, sized via the width/height
    // ATTRIBUTES (no viewBox, no CSS-driven stretching) so 1 SVG unit is
    // exactly 1 CSS pixel with zero scale transform involved. Combined with
    // shape-rendering="crispEdges" on the root <svg> (set once in the HTML),
    // every stroke edge — both ticks included — snaps to the same device
    // pixel grid, so they always render at an identical width, unlike two
    // separate CSS box-model elements which can each get rounded slightly
    // differently by the browser's own layout engine.
    export function drawDimLineSvg(svgId, width) {
      const svg = document.getElementById(svgId);
      if (!svg) return;
      const h = 15;
      const w = Math.max(0, Math.round(width));
      svg.setAttribute('width', w);
      svg.setAttribute('height', h);
      if (w === 0) { svg.innerHTML = ''; return; }
      const stroke = 'style="stroke:var(--primary-color);"';
      svg.innerHTML =
        `<line x1="1" y1="0" x2="1" y2="${h}" stroke-width="2" ${stroke}></line>` +
        `<line x1="${w - 1}" y1="0" x2="${w - 1}" y2="${h}" stroke-width="2" ${stroke}></line>` +
        `<line x1="0" y1="${h / 2}" x2="${w}" y2="${h / 2}" stroke-width="2.5" ${stroke}></line>`;
    }

    // Keeps a testament's "OLD TESTAMENT"/"NEW TESTAMENT" label centered in
    // whatever part of its dimension line is actually scrolled into view,
    // instead of centered on the line's full width. On a wide desktop
    // viewport the whole line (and the label with it) usually fits on screen
    // at once, so this rarely visibly matters there — but on a narrow mobile
    // screen the shelf can be scrolled across a line many times the
    // viewport's own width, and a label fixed to the line's midpoint then
    // sits far outside whatever sliver is currently visible, effectively
    // never showing up. Hidden entirely (rather than clamped to an edge)
    // when the section isn't in view at all, so it doesn't sit pinned to the
    // wrong content while the user is scrolled elsewhere.
    export function positionDimLabel(labelId, sectionStart, sectionWidth, viewportWidth, scrollLeft) {
      const label = document.getElementById(labelId);
      if (!label) return;
      const sectionEnd = sectionStart + sectionWidth;
      const visibleStart = Math.max(sectionStart, scrollLeft);
      const visibleEnd = Math.min(sectionEnd, scrollLeft + viewportWidth);
      if (sectionWidth <= 0 || visibleStart >= visibleEnd) {
        label.style.display = 'none';
        return;
      }
      label.style.display = '';
      let midpoint = (visibleStart + visibleEnd) / 2;

      // The label's own rendered width isn't factored into that midpoint, so on
      // a narrow (mobile) viewport — where only a sliver of this testament's
      // line is scrolled into view — centering on that sliver can push half the
      // label past the viewport's own edge, where .bible-study-ruler-viewport's
      // overflow:hidden then clips it (e.g. "OLD TESTAMENT" bleeding off-screen
      // as just "TESTAMENT"). Clamp the label's center so its full width stays
      // inside the viewport whenever there's room to. label.offsetWidth forces a
      // layout read here, but this only runs on render/scroll for two labels.
      const halfLabelWidth = label.offsetWidth / 2;
      const viewportMin = scrollLeft + halfLabelWidth;
      const viewportMax = scrollLeft + viewportWidth - halfLabelWidth;
      if (viewportMin <= viewportMax) {
        midpoint = Math.min(Math.max(midpoint, viewportMin), viewportMax);
      }

      label.style.left = Math.round(midpoint - sectionStart) + 'px';
    }

    // Re-reads the shelf's current scroll position (and the last metrics
    // renderBibleStudyRuler computed) to reposition both testament labels —
    // called on every render AND on every scroll tick, since which slice of
    // each line is visible changes continuously as the shelf scrolls.
    export function updateBibleStudyDimLabels() {
      const shelf = document.getElementById('bible-study-shelf');
      const viewport = document.getElementById('bible-study-ruler-viewport');
      if (!shelf || !viewport) return;
      const viewportWidth = viewport.getBoundingClientRect().width;
      const scrollLeft = shelf.scrollLeft;
      positionDimLabel('bible-study-dim-label-ot', bibleStudyRulerMetrics.otStart, bibleStudyRulerMetrics.otWidth, viewportWidth, scrollLeft);
      positionDimLabel('bible-study-dim-label-nt', bibleStudyRulerMetrics.ntStart, bibleStudyRulerMetrics.ntWidth, viewportWidth, scrollLeft);
    }

    export function renderBibleStudyRuler() {
      const shelf = document.getElementById('bible-study-shelf');
      const track = document.getElementById('bible-study-ruler-track');
      const viewport = document.getElementById('bible-study-ruler-viewport');
      const leadSpacer = document.getElementById('bible-study-ruler-lead');
      const midSpacer = document.getElementById('bible-study-ruler-mid');
      const otSection = document.getElementById('bible-study-legend-section-ot');
      const ntSection = document.getElementById('bible-study-legend-section-nt');
      if (!shelf || !track || !viewport || !leadSpacer || !midSpacer || !otSection || !ntSection) return;

      function spineEl(title) {
        const i = BIBLE_STUDIES_BOOK_ORDER.indexOf(title);
        return i === -1 ? null : document.getElementById(`book-spine-${i}`);
      }
      const genesisEl = spineEl('Genesis'), malachiEl = spineEl('Malachi');
      const matthewEl = spineEl('Matthew'), revelationEl = spineEl('Revelation');
      if (!genesisEl || !malachiEl || !matthewEl || !revelationEl) {
        // Shouldn't normally happen (the book order is a fixed constant) — hide
        // the ruler rather than show something misaligned.
        viewport.style.display = 'none';
        return;
      }
      viewport.style.display = '';

      // Each section (dimension line + its color-code swatches, stacked) and
      // the spacers before/between them are sized to the real on-shelf pixel
      // span of their boundary books, so the line, the swatches below it, AND
      // the gap that precedes them all sit exactly where those books are —
      // and, since they're laid out in normal flow inside one flex track that
      // gets shifted by shelf's own scrollLeft, they slide along with the
      // shelf as a single unit rather than needing separate tracking.
      const shelfRect = shelf.getBoundingClientRect();
      function left(el) { return el.getBoundingClientRect().left - shelfRect.left + shelf.scrollLeft; }
      function right(el) { return el.getBoundingClientRect().right - shelfRect.left + shelf.scrollLeft; }

      // Rounded to whole pixels: getBoundingClientRect can return fractional
      // values (sub-pixel flex layout, device pixel ratio), and a fractional
      // width/position on a thin 2px tick lands it on a half-pixel boundary,
      // which the browser then anti-aliases — making that one tick render
      // visibly thinner/blurrier than its neighbor. Whole pixels keep both
      // ticks on the same crisp footing.
      const genesisLeft = Math.round(left(genesisEl));
      const malachiRight = Math.round(right(malachiEl));
      const matthewLeft = Math.round(left(matthewEl));
      const revelationRight = Math.round(right(revelationEl));

      const otWidth = Math.max(0, malachiRight - genesisLeft);
      const ntWidth = Math.max(0, revelationRight - matthewLeft);

      leadSpacer.style.width = Math.max(0, genesisLeft) + 'px';
      otSection.style.width = otWidth + 'px';
      midSpacer.style.width = Math.max(0, matthewLeft - malachiRight) + 'px';
      ntSection.style.width = ntWidth + 'px';

      drawDimLineSvg('bible-study-dim-line-ot-svg', otWidth);
      drawDimLineSvg('bible-study-dim-line-nt-svg', ntWidth);

      bibleStudyRulerMetrics = {
        otStart: Math.max(0, genesisLeft),
        otWidth: otWidth,
        ntStart: matthewLeft,
        ntWidth: ntWidth
      };

      track.style.transform = `translateX(${-Math.round(shelf.scrollLeft)}px)`;
      updateBibleStudyDimLabels();

      if (!bibleStudyRulerScrollBound) {
        shelf.addEventListener('scroll', () => {
          const t = document.getElementById('bible-study-ruler-track');
          if (t) t.style.transform = `translateX(${-Math.round(shelf.scrollLeft)}px)`;
          updateBibleStudyDimLabels();
        });
        bibleStudyRulerScrollBound = true;
      }
    }

