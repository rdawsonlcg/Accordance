    export async function saveBookAdminForm() {
      if (!currentUser || !currentUser.isAdmin) return;
      const title = document.getElementById('book-admin-select').value;
      if (!title) { alert('Choose a book first.'); return; }

      if (bookAdminSessionsState.some(s => !s.title.trim())) {
        alert('Every session needs a title.');
        return;
      }

      const colorInput = document.getElementById('book-admin-color').value;
      const heightInput = parseInt(document.getElementById('book-admin-height').value, 10) || 195;

      // Resolve the Shelf Group picker into an actual shelf_group_id, creating a
      // new group or propagating an edited color/height to an existing group's
      // other books along the way — see handleBookAdminShelfGroupChange for what
      // each option means.
      const shelfGroupSelectVal = document.getElementById('book-admin-shelf-group').value;
      let shelfGroupId = null;

      if (shelfGroupSelectVal === '__new__') {
        const newGroupName = document.getElementById('book-admin-new-group-name').value.trim();
        if (!newGroupName) { alert('Give the new shelf group a name.'); return; }
        const existingByName = bookShelfGroupsList.find(g => g.name.toLowerCase() === newGroupName.toLowerCase());
        if (existingByName) {
          // Someone already created this group name (maybe in another tab) — join it
          // instead of erroring, propagating this color/height if they've changed.
          shelfGroupId = existingByName.id;
          if (existingByName.color !== colorInput || existingByName.height !== heightInput) {
            const ok = await updateBookShelfGroupColorHeight(shelfGroupId, colorInput, heightInput);
            if (!ok) return;
          }
        } else {
          const { data: newGroup, error: groupError } = await bookShelfGroupsTable.insert(
            { name: newGroupName, color: colorInput, height: heightInput },
            'id, name, color, height'
          );
          if (groupError) {
            console.error('Error creating shelf group:', groupError.message);
            alert('Could not create the shelf group: ' + groupError.message);
            return;
          }
          bookShelfGroupsList.push(newGroup);
          bookShelfGroupsList.sort((a, b) => a.name.localeCompare(b.name));
          shelfGroupId = newGroup.id;
        }
      } else if (shelfGroupSelectVal) {
        shelfGroupId = parseInt(shelfGroupSelectVal, 10);
        const group = bookShelfGroupsList.find(g => g.id === shelfGroupId);
        if (group && (group.color !== colorInput || group.height !== heightInput)) {
          const ok = await updateBookShelfGroupColorHeight(shelfGroupId, colorInput, heightInput);
          if (!ok) return;
        }
      }
      // else: "No group" — shelfGroupId stays null and colorInput/heightInput
      // below are just this one book's own color/height, as before.

      const presenters = bookAdminPresentersState
        .filter(p => p.name.trim())
        .map(p => ({ name: p.name.trim(), photo: p.photo.trim() }));

      const sessions = bookAdminSessionsState.map(s => {
        const item = { title: s.title.trim(), type: s.type };
        if (s.type === 'audio') item.audio = s.url.trim();
        else if (s.type === 'video') item.video = s.url.trim();
        else if (s.type === 'print' || s.type === 'study_guide') item.article = s.url.trim();
        if (s.presenterName.trim()) {
          item.presenter = { name: s.presenterName.trim(), photo: s.presenterPhoto.trim() };
        }
        return item;
      });

      const payload = {
        book: title,
        color: colorInput,
        height: heightInput,
        live: document.getElementById('book-admin-live').checked,
        shelf_group_id: shelfGroupId,
        presenters: presenters,
        sessions: sessions,
        updated_at: new Date().toISOString()
      };

      const { data, error } = await bibleStudyBooksTable.upsert(
        payload,
        'id, book, color, height, live, shelf_group_id, presenters, sessions',
        { onConflict: 'book' }
      );

      if (error) {
        console.error('Error saving book content:', error.message);
        alert('Could not save: ' + error.message);
        return;
      }

      bibleStudyDbBooks[title] = {
        dbId: data.id,
        color: data.color,
        height: data.height,
        live: !!data.live,
        shelfGroupId: data.shelf_group_id,
        presenters: data.presenters || [],
        sessions: data.sessions || []
      };

      // Register any presenter typed in by hand (name + photo, both filled in) into the
      // reusable directory so they show up in the dropdown for every future book.
      for (const p of presenters) {
        await upsertStudyPresenter(p.name, p.photo);
      }
      for (const s of sessions) {
        if (s.presenter && s.presenter.name && s.presenter.photo) {
          await upsertStudyPresenter(s.presenter.name, s.presenter.photo);
        }
      }

      updateStudyNotificationBadges();
      alert(`Saved! "${title}" is now live for everyone.`);
      closeBookAdminView();
      switchStudySubTab('bible-studies');
      selectBibleStudyBook(title, true);
    }

